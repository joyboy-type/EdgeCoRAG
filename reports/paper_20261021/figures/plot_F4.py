#!/usr/bin/env python3
"""Reproduce F4 from bf16_cast_ablation.json only (no models/images/GPU).

Requires matplotlib and NumPy; does not install packages. Example:
  python reports/paper_20261021/figures/plot_F4.py --output-dir /path/to/new/F4
The default output directory is this script's directory. Existing SVG/PNG are
never overwritten: choose a fresh --output-dir to compare hashes. Font defaults
to an existing macOS CJK font; use --font /path/to/CJK-font.ttf on other systems.
SVG uses a fixed hash salt and no date metadata for reproducible same-stack runs.
Matplotlib/FreeType/font differences can still change bytes; PNG is 150 dpi.

Verification at 161230c using matplotlib 3.11.2 / NumPy 2.5.4 / STHeiti Medium:
  PNG matches committed SHA256 exactly:
    e8de4fa76aa64d01179c48d1e30cffac7d2394a230eda2463c3e06a11c62cb35
  SVG committed SHA256:
    aa6dd141fdfe4fa9a65b419ef73916674e218770e042be0c38c810b054f1666a
  SVG rerun SHA256:
    457f496f7bd211cb40ebfb9c06be91473ac33c3e11f6b95cab22d825e59af2af
  SVG differences: Date metadata omitted and autogenerated IDs fixed by
  svg.hashsalt; version unchanged. Drawing attributes match after metadata
  exclusion and generated-ID remapping. Committed figures were not overwritten.

"""
import argparse
import hashlib
import itertools
import json
from pathlib import Path
import sys
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.font_manager import FontProperties
import numpy as np

parser=argparse.ArgumentParser(description=__doc__)
repo=Path(__file__).resolve().parents[3]
parser.add_argument('--input',type=Path,default=repo/'reports/next_stage_20261019/order_diff_20261021/bf16_cast_ablation.json')
parser.add_argument('--output-dir',type=Path,default=Path(__file__).resolve().parent)
parser.add_argument('--font',type=Path)
args=parser.parse_args()
out=args.output_dir
for name in ['F4_order_consistency.svg','F4_order_consistency.png']:
    if (out/name).exists():
        parser.error('Refusing to overwrite '+str(out/name)+'; use a fresh --output-dir')
font=args.font
if font is None:
    candidates=[Path('/System/Library/Fonts/STHeiti Medium.ttc'),Path('/System/Library/Fonts/Supplemental/Songti.ttc')]
    font=next((p for p in candidates if p.is_file()),None)
if font is None or not font.is_file():
    parser.error('Existing CJK font required; supply --font')
fontpath=str(font)
r=json.loads(args.input.read_text(encoding='utf-8'))
qs=['10','1049','1051','1062','1117'];overlap=[];inversions=[]
for q in qs:
    item=next(x for x in r['queries'] if x['qid']=='mragb:'+q)
    a=[x['sha256_q95'] for x in item['fp32_top10']]
    b=item['history']['mapped_top10'];common=set(a)&set(b)
    overlap.append(len(common))
    inversions.append(sum(b.index(x)>b.index(y) for x,y in itertools.combinations([x for x in a if x in common],2)))
    if overlap[-1]!=item['history']['top10_shared_with_fp32']:
        raise ValueError('Registered overlap inconsistent for '+q)
if overlap!=[3,7,6,1,3] or inversions!=[1,0,2,0,0]:
    raise ValueError('Input no longer matches registered F4 scope')
flips=sum(x['changed_order'] for x in r['queries'])
if flips!=0 or format(r['max_cast_uplift_shared_history_candidates'],'.1e')!='1.1e-03':
    raise ValueError('bf16-cast registered scope changed')
if not all(len(x['fp32_top10'])==10 for x in r['queries']):
    raise ValueError('Expected top10 scope')
if r['pool_overlap']['history_keys_rows']!=18955 or r['pool_overlap']['live_unique_q95']!=4712:
    raise ValueError('Unexpected pool sizes')
plt.rcParams['svg.hashsalt']='edgecorag-F4-order-consistency-v1'

plt.rcParams.update({'font.family':'sans-serif','font.size':10,'axes.unicode_minus':False,'svg.fonttype':'path','hatch.linewidth':.8,'savefig.facecolor':'white'})
fp=lambda size:FontProperties(fname=fontpath,size=size)
fig,ax=plt.subplots(figsize=(12,6.5));fig.subplots_adjust(left=.08,right=.97,top=.77,bottom=.25)
x=np.arange(len(qs));w=.28
bars1=ax.bar(x-w/2,overlap,w,facecolor='white',edgecolor='black',linewidth=1.2,hatch='///',label='映射后重合数（张）',zorder=3)
bars2=ax.bar(x+w/2,inversions,w,facecolor='.75',edgecolor='black',linewidth=1.2,hatch='xxx',label='换位对数（对）',zorder=3)
for bars in [bars1,bars2]:
 for bar in bars:
  h=bar.get_height();ax.text(bar.get_x()+bar.get_width()/2,h+.18,str(int(h)),ha='center',va='bottom',fontsize=11)
ax.plot(x,[flips]*len(x),color='black',linestyle='--',marker='D',markersize=4,linewidth=1.1,label='bf16-cast 同池翻转对数',zorder=4)
ax.axhline(10,color='black',linestyle=':',linewidth=1)
ax.text(4.42,10,'候选基数 10',ha='right',va='bottom',fontproperties=fp(9),bbox={'facecolor':'white','edgecolor':'none','pad':1})
ax.set_xticks(x,qs);ax.set_yticks([0,2,6,10]);ax.set_ylim(-.25,10.9);ax.set_xlim(-.6,4.6)
ax.set_xlabel('题号',fontproperties=fp(11),labelpad=9);ax.set_ylabel('候选数/对数',fontproperties=fp(11));ax.grid(axis='y',color='.85',linewidth=.6,zorder=0)
ax.spines[['top','right']].set_visible(False)
ax.legend(loc='upper left',prop=fp(9),frameon=True,facecolor='white',edgecolor='black',framealpha=1,ncol=1)
fig.suptitle('F4 排序一致性：跨池映射与同池精度消融',fontproperties=fp(15),y=.96)
fig.text(.5,.865,'bf16-cast 同池消融：0 翻转，最大抬升 1.1e-3（history 共有候选）',ha='center',fontproperties=fp(11),bbox={'boxstyle':'square,pad=.6','facecolor':'white','edgecolor':'black','linewidth':1})
fig.text(.08,.105,'这五题的 history 来自 18,955 池、live 来自 4,712 池；重合数是按 sha256_raw→sha256_q95 映射后的结果，属跨池比较。',fontproperties=fp(9),ha='left')
fig.text(.08,.06,'1062 仅重合 1 张，不构成换位样本。',fontproperties=fp(9),ha='left')

out.mkdir(parents=True,exist_ok=True)
source='bf16_cast_ablation.json: queries[].history.top10_shared_with_fp32; inversions derived from queries[].fp32_top10[].sha256_q95 and history.mapped_top10; flips=sum(changed_order); max_cast_uplift_shared_history_candidates. cross_pool_mapped.json absent at e35d11f; same requested counts independently verified from registered mapped sequences.'
svg=out/'F4_order_consistency.svg';png=out/'F4_order_consistency.png'
fig.savefig(svg,metadata={'Title':'F4 排序一致性','Description':source,'Date':None})
# Trim generator trailing spaces; drawing/path tokens are unchanged.
svg.write_text('\n'.join(line.rstrip() for line in svg.read_text(encoding='utf-8').splitlines())+'\n',encoding='utf-8')
fig.savefig(png,dpi=150,metadata={'Description':source})
plt.close(fig)
print(json.dumps({'input_sha256':hashlib.sha256(args.input.read_bytes()).hexdigest(),
    'matplotlib':matplotlib.__version__,'numpy':np.__version__,
    'font_sha256':hashlib.sha256(font.read_bytes()).hexdigest(),
    'output_sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [svg,png]},
    'determinism':'fixed SVG hashsalt; Date metadata omitted; same rendering stack required'},ensure_ascii=False,indent=2))
